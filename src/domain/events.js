// 弹着作废原因码（ISSf 裁判语境）
export const VOID_REASONS = Object.freeze({
  CALIBRATION_DRIFT: "CALIBRATION_DRIFT", // 靶位校准漂移
  EQUIPMENT_FAILURE: "EQUIPMENT_FAILURE", // 器材故障
  PROTEST_UPHELD: "PROTEST_UPHELD", // 申诉成立
  RULE_INFRINGEMENT: "RULE_INFRINGEMENT", // 违例弹
  SCORING_ERROR: "SCORING_ERROR", // 计分系统错误
});

export function createEvent(type, payload, meta = {}) {
  if (!type || !EVENT_TYPES[type]) throw new Error(`未知事件类型: ${String(type)}`);
  if (!meta.atUtc) throw new Error("事件必须带 atUtc 时刻");
  return {
    type,
    ...structuredClone(payload),
    atUtc: meta.atUtc,
    actorId: meta.actorId ?? null,
    actorRole: meta.actorRole ?? null,
    source: meta.source ?? "manual",
  };
}
