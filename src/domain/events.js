//   原始流     SHOT_RECORDED（电子靶）/ SHOTS_SIGNED（裁判签名覆盖）
//   追加修正   SHOT_VOIDED / RESHOT_AWARDED / PENALTY_DEDUCTED / ATHLETE_WITHDRAWN
//   申诉       PROTEST_FILED / PROTEST_RESOLVED
//   认定链     DISPLAY_SNAPSHOT_FROZEN / GATE_EVIDENCE_SUBMITTED /
//              MEDIA_FLASH_PUBLISHED / VERSION_PUBLISHED / VERSION_CERTIFIED /
//              RECORD_RATIFIED

